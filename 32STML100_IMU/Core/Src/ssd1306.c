static void SSD1306_WriteCmd(SSD1306_t *d, uint8_t cmd)
{
    uint8_t buf[2] = { 0x00, cmd }; /* control byte: Co=0, D/C=0 (command) */
    HAL_I2C_Master_Transmit(d->hi2c, SSD1306_ADDR, buf, 2, 100);
}

HAL_StatusTypeDef SSD1306_Init(SSD1306_t *d, I2C_HandleTypeDef *hi2c)
{
    d->hi2c = hi2c;

    /* Init sequence common for 128x32 */
    SSD1306_WriteCmd(d, SSD1306_CMD_DISPLAYOFF);
    SSD1306_WriteCmd(d, SSD1306_CMD_SETDISPLAYCLOCKDIV);
    SSD1306_WriteCmd(d, 0x80);
    SSD1306_WriteCmd(d, SSD1306_CMD_SETMULTIPLEX);
    SSD1306_WriteCmd(d, 0x1F);                    /* 0x1F = 32 rows - 1 */
    SSD1306_WriteCmd(d, SSD1306_CMD_SETDISPLAYOFFSET);
    SSD1306_WriteCmd(d, 0x00);
    SSD1306_WriteCmd(d, SSD1306_CMD_SETSTARTLINE | 0x00);
    SSD1306_WriteCmd(d, SSD1306_CMD_CHARGEPUMP);
    SSD1306_WriteCmd(d, 0x14);                    /* enable charge pump */
    SSD1306_WriteCmd(d, SSD1306_CMD_MEMORYMODE);
    SSD1306_WriteCmd(d, 0x00);                    /* horizontal addressing */
    SSD1306_WriteCmd(d, SSD1306_CMD_SEGREMAP | 0x01);
    SSD1306_WriteCmd(d, SSD1306_CMD_COMSCANDEC);
    SSD1306_WriteCmd(d, SSD1306_CMD_SETCOMPINS);
    SSD1306_WriteCmd(d, 0x02);                    /* for 128x32 */
    SSD1306_WriteCmd(d, SSD1306_CMD_SETCONTRAST);
    SSD1306_WriteCmd(d, 0x7F);
    SSD1306_WriteCmd(d, SSD1306_CMD_SETPRECHARGE);
    SSD1306_WriteCmd(d, 0xF1);
    SSD1306_WriteCmd(d, SSD1306_CMD_SETVCOMDETECT);
    SSD1306_WriteCmd(d, 0x40);
    SSD1306_WriteCmd(d, SSD1306_CMD_DISPLAYALLON_RESUME);
    SSD1306_WriteCmd(d, SSD1306_CMD_NORMALDISPLAY);
    SSD1306_WriteCmd(d, SSD1306_CMD_DISPLAYON);

    SSD1306_Clear(d);
    return SSD1306_Update(d);
}

void SSD1306_Clear(SSD1306_t *d)
{
    memset(d->buf, 0x00, sizeof(d->buf));
}

void SSD1306_DrawPixel(SSD1306_t *d, uint8_t x, uint8_t y, uint8_t on)
{
    if (x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT)
        return;

    uint16_t idx = x + ((y / 8) * SSD1306_WIDTH);
    if (on)
        d->buf[idx] |= (1 << (y % 8));
    else
        d->buf[idx] &= ~(1 << (y % 8));
}

void SSD1306_DrawChar(SSD1306_t *d, uint8_t x, uint8_t y, char c, uint8_t on)
{
    if (c < 32 || c > 127)
        c = ' ';

    for (uint8_t i = 0; i < 5; i++)
    {
        uint8_t col = font5x7[c - 32][i];
        for (uint8_t r = 0; r < 7; r++)
        {
            if (col & (1 << r))
                SSD1306_DrawPixel(d, x + i, y + r, on);
            else
                SSD1306_DrawPixel(d, x + i, y + r, on ? 0 : 1);
        }
    }
}

void SSD1306_DrawString(SSD1306_t *d, uint8_t x, uint8_t y, const char *str, uint8_t on)
{
    while (*str)
    {
        SSD1306_DrawChar(d, x, y, *str, on);
        x += 6;
        if (x + 6 >= SSD1306_WIDTH)
            break;
        str++;
    }
}

HAL_StatusTypeDef SSD1306_Update(SSD1306_t *d)
{
    uint8_t cmd[3];

    cmd[0] = 0x00;
    cmd[1] = 0x21; /* column address */
    cmd[2] = 0x00;
    HAL_I2C_Master_Transmit(d->hi2c, SSD1306_ADDR, cmd, 3, 100);
    cmd[1] = 0x7F;
    HAL_I2C_Master_Transmit(d->hi2c, SSD1306_ADDR, cmd, 3, 100);

    cmd[1] = 0x22; /* page address */
    cmd[2] = 0x00;
    HAL_I2C_Master_Transmit(d->hi2c, SSD1306_ADDR, cmd, 3, 100);
    cmd[1] = 0x03;
    HAL_I2C_Master_Transmit(d->hi2c, SSD1306_ADDR, cmd, 3, 100);

    return HAL_I2C_Mem_Write(d->hi2c, SSD1306_ADDR, 0x40, I2C_MEMADD_SIZE_8BIT,
                             d->buf, sizeof(d->buf), 100);
}
